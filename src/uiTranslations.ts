export const UI_LABELS: Record<UILanguage, Record<LabelKey, string>> = { en, de }

export type TranslationParams = Record<string, string | number>
export type Translate = (key: LabelKey, params?: TranslationParams) => string

export function translate(language: UILanguage, key: LabelKey, params?: TranslationParams): string {
  const template = UI_LABELS[language][key] ?? UI_LABELS.en[key]
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match))
}

export const createTranslator = (language: UILanguage): Translate => (key, params) => translate(language, key, params)

export function parseUILanguage(value: string | null): UILanguage {
  return value === 'de' ? 'de' : 'en'
}

export function readStoredUILanguage(): UILanguage {
  try {
    return parseUILanguage(window.localStorage.getItem(UI_LANGUAGE_STORAGE_KEY))
  } catch {
    return 'en'
  }
}

